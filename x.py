def command_gui(args: argparse.Namespace) -> None:
    build_gui(args)


def command_firmware(args: argparse.Namespace) -> None:
    generate_version_files()
    build_firmware_targets(args.board, flash=args.flash, port=args.port)


def copytree_merge(src: Path, dst: Path) -> None:
    if not src.exists():
        return
    for item in src.rglob("*"):
        rel = item.relative_to(src)
        out = dst / rel
        if item.is_dir():
            out.mkdir(parents=True, exist_ok=True)
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, out)


def should_copy_runtime_file(path: Path) -> bool:
    if any(part in PACKAGE_EXCLUDE_DIRS for part in path.parts):
        return False
    if path.suffix.lower() in PACKAGE_EXCLUDE_SUFFIXES:
        return False
    return True


def copy_runtime_tree(src: Path, dst: Path) -> None:
    if not src.exists():
        raise FileNotFoundError(f"missing runtime directory: {src}")
    for item in src.rglob("*"):
        if item.is_dir() or not should_copy_runtime_file(item.relative_to(src)):
            continue
        rel = item.relative_to(src)
        out = dst / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, out)


def copy_file_if_exists(src: Path, dst: Path, required: bool = False) -> bool:
    if not src.exists():
        if required:
            raise FileNotFoundError(f"missing required file: {src}")
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return True


def publish_gui(config: str, out_dir: Path, runtime: str) -> None:
    remove_tree(out_dir)
    run_process([
        "dotnet", "publish", str(GUI_PROJECT),
        "-c", config,
        "-r", runtime,
        "--self-contained", "false",
        "-o", str(out_dir),
    ])


