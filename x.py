def collect_checksums(out_root: Path) -> list[dict[str, str | int]]:
    entries: list[dict[str, str | int]] = []
    for file in sorted(p for p in out_root.rglob("*") if p.is_file()):
        if file.name in {"checksums.sha256", "package-manifest.json"}:
            continue
        digest = hashlib.sha256(file.read_bytes()).hexdigest()
        rel = file.relative_to(out_root).as_posix()
        entries.append({"path": rel, "size": file.stat().st_size, "sha256": digest})
    return entries


def write_manifest(out_root: Path, package_name: str, runtime: str) -> None:
    files = collect_checksums(out_root)
    (out_root / "checksums.sha256").write_text(
        "".join(f"{item['sha256']}  {item['path']}\n" for item in files),
        encoding="utf-8",
    )
    manifest = {
        "name": "OpenFinger",
        "version": version(),
        "protocol_version": protocol_version(),
        "runtime": runtime,
        "package": package_name,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "entrypoint": "OpenFinger.Control.exe",
        "files": files,
    }
    (out_root / "package-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def create_zip_archive(src_dir: Path, archive: Path) -> None:
    if archive.exists():
        archive.unlink()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for file in sorted(p for p in src_dir.rglob("*") if p.is_file()):
            zf.write(file, file.relative_to(src_dir.parent).as_posix())


def create_tar_gz_archive(src_dir: Path, archive: Path) -> None:
    if archive.exists():
        archive.unlink()
    with tarfile.open(archive, "w:gz") as tar:
        tar.add(src_dir, arcname=src_dir.name)


def command_package(args: argparse.Namespace) -> None:
    if not args.skip_build:
        command_build(args)

    v = version()
    runtime = args.runtime
    package_name = f"OpenFinger-{v}-{runtime}"
    out_root = DIST / package_name
    remove_tree(out_root)
    out_root.mkdir(parents=True, exist_ok=True)

    # OpenFinger.Control is the product entry point, so publish it directly at
    # the package root. This keeps the GitHub asset usable after one extract:
    # users can open the folder and run OpenFinger.Control.exe immediately.
    publish_gui(args.config, out_root, runtime)

    native_dir = BUILD / args.config
    for name in PACKAGE_NATIVE_TOOLS:
        copy_file_if_exists(native_dir / name, out_root / name, required=True)
    for name in BRIDGE_RUNTIME_FILES:
        copy_file_if_exists(native_dir / name, out_root / name, required=False)

    copy_runtime_tree(DRIVER_ROOT, out_root / "Driver")
    for junk in (out_root / "Driver" / "bin" / "win64" / args.config,):
        remove_tree(junk)

    docs_dir = ROOT / "docs"
    if docs_dir.exists():
        copy_runtime_tree(docs_dir, out_root / "docs")
    copy_file_if_exists(ROOT / "README.md", out_root / "docs" / "README.md")
    copy_file_if_exists(ROOT / "CHANGELOG.md", out_root / "docs" / "CHANGELOG.md")
    copy_file_if_exists(ROOT / "LICENSE", out_root / "LICENSE")

    write_package_readme(out_root, package_name, runtime)
    # Keep machine-oriented files out of the user-facing archive. CI still uses
    # verify-package to validate the layout and critical files before upload.

    archives: list[Path] = []
    formats = ["zip", "tar.gz"] if args.archive_format == "both" else [args.archive_format]
    for fmt in formats:
        archive = DIST / f"{package_name}.{fmt}"
        if fmt == "zip":
            create_zip_archive(out_root, archive)
        elif fmt == "tar.gz":
            create_tar_gz_archive(out_root, archive)
        else:
            raise ValueError(f"unknown archive format: {fmt}")
        archives.append(archive)
        print(f"[x.py] package: {archive}")

    release_notes = DIST / "release-notes.md"
    release_notes.write_text(
        f"""# OpenFinger {v}

- Runtime: `{runtime}`
- Protocol: `v{protocol_version()}`
- Entrypoint: `OpenFinger.Control.exe`

Artifacts:
""" + "".join(f"- `{a.name}`\n" for a in archives) + "\nThis release was generated by `python x.py package`.\n",
        encoding="utf-8",
    )


def command_verify_package(args: argparse.Namespace) -> None:
    package_name = f"OpenFinger-{version()}-{args.runtime}"
    out_root = DIST / package_name
    required = [
        out_root / "OpenFinger.Control.exe",
        out_root / "openfinger_service.exe",
        out_root / "openfinger_controller_bridge.exe",
        out_root / "openfinger_adc_monitor.exe",
        out_root / "openfinger_firmware_tool.exe",
        out_root / "Driver" / "driver.vrdrivermanifest",
        out_root / "README.txt",
    ]
    missing = [path for path in required if not path.exists()]
    if missing:
        raise FileNotFoundError("package verification failed; missing: " + ", ".join(str(p) for p in missing))
    forbidden_root_files = [
        out_root / "package-manifest.json",
        out_root / "checksums.sha256",
        out_root / "VERSION",
        out_root / "PROTOCOL_VERSION",
    ]
    leaked = [path for path in forbidden_root_files if path.exists()]
    if leaked:
        raise FileExistsError("package contains internal files: " + ", ".join(str(p) for p in leaked))
    print(f"[x.py] package verified: {out_root}")

def command_run(args: argparse.Namespace) -> None:
    generate_version_files()
    build_cpp(args)
    build_gui(args)
    build_firmware_targets("all", flash=False, port=None)
    launch_gui(args.config)


def command_clean(args: argparse.Namespace) -> None:
    del args
    for path in (BUILD, DIST, GUI_DIR / "bin", GUI_DIR / "obj"):
        remove_tree(path)
    for project_dir, _ in FIRMWARE_TARGETS.values():
        remove_tree(project_dir / ".pio")


def command_version(args: argparse.Namespace) -> None:
    del args
    generate_version_files()


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="OpenFinger build / firmware / package helper")
    parser.add_argument("command", nargs="?", default="build", choices=[
        "build", "driver", "service", "bridge", "monitor", "gui", "firmware", "package", "verify-package", "run", "clean", "version"
    ])
    parser.add_argument("--config", default="Debug", choices=["Debug", "Release", "RelWithDebInfo", "MinSizeRel"])
    parser.add_argument("--generator", default="Visual Studio 17 2022" if os.name == "nt" else None)
    parser.add_argument("--arch", default="x64" if os.name == "nt" else None)
    parser.add_argument("--stop", action=argparse.BooleanOptionalAction, default=os.name == "nt", help="stop OpenFinger processes before C++ build")
    parser.add_argument("--stop-steamvr", action="store_true", help="also stop vrserver/vrmonitor before build")
    parser.add_argument("--board", default="esp32c3", choices=["esp32c3", "esp32s3", "all"], help="firmware board target")
    parser.add_argument("--flash", action="store_true", help="upload firmware after build")
    parser.add_argument("--port", help="serial port for firmware flashing, for example COM5")
    parser.add_argument("--runtime", default="win-x64", help=".NET runtime identifier used by package/publish, for example win-x64")
    parser.add_argument("--archive-format", default="zip", choices=["zip", "tar.gz", "both"], help="package archive format")
    parser.add_argument("--skip-build", action="store_true", help="package existing build outputs without rebuilding")
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    handlers = {
        "build": command_build,
        "driver": command_driver,
        "service": command_service,
        "bridge": command_bridge,
        "monitor": command_monitor,
        "gui": command_gui,
        "firmware": command_firmware,
        "package": command_package,
        "verify-package": command_verify_package,
        "run": command_run,
        "clean": command_clean,
        "version": command_version,
    }
    try:
        handlers[args.command](args)
        return 0
    except subprocess.CalledProcessError as exc:
        print(f"[x.py] command failed with exit code {exc.returncode}", file=sys.stderr)
        return exc.returncode
    except Exception as exc:
        print(f"[x.py] {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
